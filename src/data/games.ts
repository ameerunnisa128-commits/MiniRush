export const GAME_CATALOG: GameDefinition[] = ALL_GAMES;

// Helper to get daily featured game
export function getDailyChallengeGame(gamesList: GameDefinition[] = ALL_GAMES): GameDefinition {
  const now = new Date();
  const dayIndex = (now.getFullYear() * 365 + now.getMonth() * 31 + now.getDate()) % 10;
  const playableGames = gamesList.filter(g => g.playable);
  return playableGames[dayIndex % playableGames.length] || gamesList[0];
}

// Helper to get weekly tournament game
export function getWeeklyTournamentGame(gamesList: GameDefinition[] = ALL_GAMES): GameDefinition {
  const playableGames = gamesList.filter(g => g.playable);
  return playableGames[2] || gamesList[0];
}

// Helper to get next game
export function getNextGame(gamesList: GameDefinition[] = ALL_GAMES, currentGameId: string): GameDefinition {
  const playableGames = gamesList.filter(g => g.playable);
  const currentIndex = playableGames.findIndex(g => g.id === currentGameId);
  const nextIndex = (currentIndex + 1) % playableGames.length;
  return playableGames[nextIndex] || gamesList[0];
}

// Helper to get weekly championship games (5 rounds)
export function getWeeklyChampionshipGames(): GameDefinition[] {
  const playableGames = ALL_GAMES.filter(g => g.playable);
  return [
    playableGames[0], // Arrow Lock
    playableGames[1], // Knife Throw
    playableGames[2], // Perfect Aim
    playableGames[3], // Perfect Park
    playableGames[4], // Mini 2048
  ];
}
